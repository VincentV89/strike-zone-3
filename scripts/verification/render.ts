function sectionDod(e: EvidenceFile): string {
  const dod = e.checks.filter((c) => c.id.startsWith('DOD-'));
  const done = dod.filter((c) => isPassed(c.status)).length;
  return `## Definition of Done (spec §17)

${String(done)} of ${String(dod.length)} rows pass. A row takes the weakest status of the checks it is composed of.

${checkTable(dod)}
`;
}

function sectionCuts(cuts: readonly Cut[]): string {
  if (cuts.length === 0)
    return '## Cuts\n\nNo features were cut. Every Should and Could item was built.\n';
  const rows = cuts.map(
    (c) =>
      `| ${escapeMd(c.story)} | ${escapeMd(c.requirement)} | ${escapeMd(c.reason)} | ${c.removedControls.map(escapeMd).join(', ')} |`,
  );
  return `## Cuts

| Story | Requirement | Reason | Removed controls |
|---|---|---|---|
${rows.join('\n')}
`;
}

function sectionLimitations(r: ReportInputs): string {
  const statics = r.limitations.map((l) => `- **${l.id}.** ${escapeMd(l.text)}`);
  const open = r.evidence.checks
    .filter((c) => !isPassed(c.status))
    .map(
      (c) => `- **${c.id}** ${escapeMd(c.title)}: ${STATUS_LABEL[c.status]}. ${escapeMd(c.reason)}`,
    );
  return `## Known Limitations

${statics.join('\n')}

### Checks that are not passed

${open.length === 0 ? 'None.' : open.join('\n')}
`;
}

export function renderReportMarkdown(r: ReportInputs): string {
  return [
    sectionHeader(r),
    sectionA(r),
    sectionB(),
    sectionC(),
    sectionD(r),
    sectionE(),
    sectionF(),
    sectionG(r),
    sectionH(),
    sectionDod(r.evidence),
    sectionCuts(r.cuts),
    sectionLimitations(r),
  ].join('\n');
}

/** Prettier with the repository options, so `npm run lint` accepts the committed file. */
export async function formatMarkdown(md: string): Promise<string> {
  return format(md, {
    parser: 'markdown',
    singleQuote: true,
    trailingComma: 'all',
    printWidth: 100,
  });
}

export async function renderReport(r: ReportInputs): Promise<string> {
  return formatMarkdown(renderReportMarkdown(r));
}
