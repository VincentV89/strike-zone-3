function testsByDirectory(v: VitestResults): string {
  const byDir = new Map<string, { total: number; passed: number }>();
  for (const f of v.files) {
    const parts = f.file.split('/');
    const dir = parts.length > 2 ? `${parts[0] ?? ''}/${parts[1] ?? ''}` : (parts[0] ?? '');
    const row = byDir.get(dir) ?? { total: 0, passed: 0 };
    row.total += f.assertions.length;
    row.passed += f.assertions.filter((a) => a.status === 'passed').length;
    byDir.set(dir, row);
  }
  const rows = [...byDir.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([dir, r]) => `| \`${dir}\` | ${String(r.total)} | ${String(r.passed)} |`);
  return ['| Directory | Tests | Passed |', '|---|---|---|', ...rows].join('\n');
}

function coverageTable(rows: readonly CoverageRow[]): string {
  const body = rows.map((r) => {
    const pct = r.lines === 0 ? 100 : (100 * r.covered) / r.lines;
    return `| \`${r.area}\` | ${String(r.covered)} / ${String(r.lines)} | ${pct.toFixed(1)} % |`;
  });
  return ['| Area | Lines covered | Line coverage |', '|---|---|---|', ...body].join('\n');
}

function matrixTable(matrix: unknown): string | null {
  if (typeof matrix !== 'object' || matrix === null || !Object.hasOwn(matrix, 'cells')) return null;
  const cells = (matrix as { cells: unknown }).cells;
  if (!Array.isArray(cells)) return null;
  const rows: string[] = [];
  for (const c of cells) {
    if (typeof c !== 'object' || c === null) continue;
    const rec = c as Record<string, unknown>;
    const cell = (k: string): string => {
      const v = Object.hasOwn(rec, k) ? rec[k] : undefined;
      return typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean'
        ? escapeMd(String(v))
        : '–';
    };
    rows.push(
      `| ${cell('map')} | ${cell('bots')} | ${cell('pass') === 'true' ? 'pass ✓' : 'fail ✕'} | ${cell('outcome')} | ${cell('ticks')} | ${cell('kills')} |`,
    );
  }
  return [
    '| Map | Bots | Cell | Outcome | Ticks | Player kills |',
    '|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function metricRows(checks: readonly CheckEvidence[]): string {
  const rows: string[] = [];
  for (const c of checks) {
    for (const e of c.refs) {
      if (e.ref.kind !== 'metric') continue;
      const ref: MetricRef = e.ref;
      const observed =
        e.observed === undefined
          ? '–'
          : typeof e.observed === 'number'
            ? String(Math.round(e.observed * 1000) / 1000)
            : escapeMd(String(e.observed));
      rows.push(
        `| ${c.id} | ${escapeMd(ref.label)} | ${ref.op} ${String(ref.target)} | ${observed} | ${e.outcome === 'pass' ? 'met' : e.outcome === 'fail' ? 'missed' : escapeMd(e.reason)} |`,
      );
    }
  }
  return [
    '| Check | Measure | Target | Observed | Result |',
    '|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function smokeSection(r: ReportInputs): string {
  const s = r.smoke;
  if (s === null) return na('npm run smoke has not run');
  if (s.mode === 'blocked') {
    return `Deployment is **blocked** (${escapeMd(s.reason ?? 'no reason')}); no deployment check counts as passed.

Missing: ${s.missing.length === 0 ? '–' : s.missing.map(escapeMd).join('; ')}

Commands for the operator:

\`\`\`sh
${OPERATOR_COMMANDS.join('\n')}
\`\`\``;
  }
  const rows = s.checks.map(
    (c) =>
      `| ${c.id} | ${escapeMd(c.request)} | ${escapeMd(c.expected)} | ${escapeMd(c.observed)} | ${c.notVerified === true ? 'not verified' : c.pass ? 'pass ✓' : 'fail ✕'} |`,
  );
  return `${isDeployedAndVerified(s.checks) ? '**Deployed and verified** (SM-1..SM-7, SM-4b and SM-9 pass).' : 'Deployed, **not verified**: at least one of SM-1..SM-7, SM-4b or SM-9 did not pass.'}

| Smoke | Request | Expected | Observed | Result |
|---|---|---|---|---|
${rows.join('\n')}`;
}

