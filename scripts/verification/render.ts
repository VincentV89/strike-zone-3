/** Escapes a value from an input file for a markdown table cell or line. */
export function escapeMd(text: string): string {
  return text
    .replace(/\r?\n/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/[|`<>[\]*_]/g, (c) => `\\${c}`);
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (typeof v === 'object' && v !== null) {
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(v).sort()) out[k] = sortKeys((v as Record<string, unknown>)[k]);
    return out;
  }
  return v;
}

export function stableJson(v: unknown): string {
  return `${JSON.stringify(sortKeys(v), null, 2)}\n`;
}

export function countTotals(checks: readonly CheckEvidence[]): Record<EvidenceStatus, number> {
  const totals = Object.fromEntries(EVIDENCE_STATUSES.map((s) => [s, 0])) as Record<
    EvidenceStatus,
    number
  >;
  for (const c of checks) totals[c.status] += 1;
  return totals;
}

export function renderEvidenceJson(e: EvidenceFile): string {
  return stableJson(e);
}

const STATUS_LABEL: Readonly<Record<EvidenceStatus, string>> = {
  'automated-pass': 'automated-pass ✓',
  'automated-fail': 'automated-fail ✕',
  'manual-pass': 'manual-pass ✓',
  'manual-fail': 'manual-fail ✕',
  'manual-pending': 'manual-pending …',
  'not-verified': 'not-verified ?',
};

function na(reason: string): string {
  return `not yet available: ${reason}`;
}

function deployBlocker(r: ReportInputs): string {
  if (r.smoke === null) return 'npm run smoke has not run';
  if (r.smoke.mode === 'blocked')
    return `deploy blocked (${r.smoke.reason ?? 'no reason recorded'})`;
  return '';
}

function liveUrl(r: ReportInputs): string | null {
  return r.smoke?.mode === 'live' && r.smoke.url !== undefined ? r.smoke.url : null;
}

function checkRow(c: CheckEvidence): string {
  return `| ${c.id} | ${escapeMd(c.title)} | ${STATUS_LABEL[c.status]}${c.indirect ? ' (indirect)' : ''} | ${escapeMd(c.reason)} |`;
}

function checkTable(checks: readonly CheckEvidence[]): string {
  return ['| Id | Check | Status | Evidence |', '|---|---|---|---|', ...checks.map(checkRow)].join(
    '\n',
  );
}

function sectionHeader(r: ReportInputs): string {
  const e = r.evidence;
  const inputs = e.inputs
    .map((i) => `| \`${i.file}\` | ${i.present ? 'present' : 'absent'} | ${i.mtime ?? '–'} |`)
    .join('\n');
  const totals = EVIDENCE_STATUSES.map((s) => `${s} ${String(e.totals[s])}`).join(', ');
  return `# StrikeZone — Final Report

Generated by \`npm run report\` from the files below. Do not edit by hand; regenerate it instead (BR-VE-55). Only **automated-pass** and **manual-pass** count as passed (BR-VE-20).

- Version: ${escapeMd(r.packageVersion)}
- Evidence run started: ${e.generatedAt}
- Test run: ${e.runFailed ? '**FAILED** (Vitest reported success: false)' : 'passed'}${e.stale ? '; **results are stale** (a source file is newer than the test run)' : ''}
- Lockfile SHA-256: ${e.lockfileSha256 ?? 'unavailable'}
- Register totals: ${totals}
${e.problems.length > 0 ? `- Problems: ${e.problems.map(escapeMd).join('; ')}\n` : ''}
| Input | State | Modified |
|---|---|---|
${inputs}
`;
}

